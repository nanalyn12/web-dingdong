/**
 * 교수자 가이드의 내용. 순수 데이터 — 화면(_app.guide.tsx)은 이것을 그리기만 한다.
 *
 * 코치마크는 "이 버튼이 무엇인지"를 한 화면 안에서 짚고 사라진다. 교수자가
 * 헷갈리는 것은 여러 화면에 걸치고 중간에 기다림이 끼는 "일의 순서"라서, 그
 * 순서를 언제든 다시 펼쳐 볼 수 있게 여기에 적는다.
 *
 * 안내문은 기능이 바뀌면 조용히 틀린 말이 된다 — 학습송 화면이 MP4 자동 생성을
 * 몇 주 동안 약속하고 있었던 것처럼. 그래서 두 가지를 테스트가 붙잡는다:
 *  - `url`·`links`는 routeTree.gen.ts에 실제로 있는 경로여야 한다.
 *  - 「」로 감싼 화면 문구는 `sources` 파일 중 하나에 글자 그대로 있어야 한다.
 * 버튼 이름을 바꾸면 가이드도 같이 고치라고 게이트가 알려준다.
 */

